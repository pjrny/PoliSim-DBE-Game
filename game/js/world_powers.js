/* ---- computed block (runs at load; plain ES5) ---------------------------
   Normalization follows the "normalization" block EXACTLY:
     linear_clamp:   score = clamp(100*(v-a0)/(a1-a0), 0, 100)
     weighted_blend: weighted mean of component clamps
   Null raw values -> null scores, skipped in all means.                    */
(function () {
  'use strict';
  var WP = window.WORLD_POWERS;
  if (!WP || !WP.nations || !WP.normalization) return;
  /* Canonical determinant order — must match ENGINE.DET_IDS (js/engine.js). */
  var DET_IDS = ['education', 'innovation', 'competitiveness', 'military', 'trade', 'output', 'fincenter', 'reserve_fx'];

  function clampScore(v, a0, a1) {
    if (v === null || v === undefined || isNaN(v)) return null;
    var s = 100 * (v - a0) / (a1 - a0);
    if (s < 0) s = 0; else if (s > 100) s = 100;
    return s;
  }

  function round1(x) { return Math.round(x * 10) / 10; }

  /* One determinant score for one nation-year. Determinants declared as a
     single source_metric are treated as a one-component blend. */
  function detScore(nat, spec, year) {
    if (!spec) return null;
    var comps = spec.components;
    if (!comps) comps = [{ metric: spec.source_metric, weight: 1, a0: spec.a0, a1: spec.a1 }];
    var sum = 0, wsum = 0;
    for (var i = 0; i < comps.length; i++) {
      var c = comps[i];
      var series = nat[c.metric];
      var v = series ? series[year] : null;
      var s = clampScore(v, c.a0, c.a1);
      if (s === null) continue; // null raw -> skipped in the weighted mean
      sum += c.weight * s;
      wsum += c.weight;
    }
    return wsum > 0 ? sum / wsum : null;
  }

  WP.det = {};       /* nation -> year -> { education..reserve_fx } (0-100 or null) */
  WP.composite = {}; /* nation -> year -> S (mean of available det scores, 0-100) */
  WP.S_latest = {};  /* nation -> S at the latest year with data */

  Object.keys(WP.nations).forEach(function (nid) {
    var nat = WP.nations[nid];
    var yearSet = {};
    Object.keys(nat).forEach(function (metric) {
      var series = nat[metric];
      if (!series) return;
      Object.keys(series).forEach(function (y) { yearSet[y] = true; });
    });
    var years = Object.keys(yearSet).sort();
    WP.det[nid] = {};
    WP.composite[nid] = {};
    var latest = null;
    years.forEach(function (y) {
      var d = {}, sum = 0, n = 0;
      DET_IDS.forEach(function (det) {
        var s = detScore(nat, WP.normalization[det], y);
        d[det] = s === null ? null : round1(s);
        if (s !== null) { sum += s; n++; }
      });
      WP.det[nid][y] = d;
      WP.composite[nid][y] = n ? round1(sum / n) : null;
      if (WP.composite[nid][y] !== null) latest = WP.composite[nid][y];
    });
    WP.S_latest[nid] = latest;
  });
})();
